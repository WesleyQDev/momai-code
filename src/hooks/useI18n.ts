export function useI18n() {
  const [locale, setLocale] = useState<string>(() => {
    try {
      return getSDK()?.i18n?.getLocale?.() || DEFAULT_LOCALE
    } catch {
      return DEFAULT_LOCALE
    }
  })

  useEffect(() => {
    try {
      const sdk = getSDK()
      if (sdk?.i18n?.onLocaleChange) {
        return sdk.i18n.onLocaleChange((newLocale) => setLocale(newLocale))
      }
    } catch {}
  }, [])

  const t = useCallback(
    (key: string): string => {
      const locDict = STRINGS[locale] || STRINGS[DEFAULT_LOCALE] || STRINGS['pt-BR']
      if (locDict[key]) return locDict[key]
      const fallbackDict = STRINGS[DEFAULT_LOCALE] || STRINGS['pt-BR']
      return fallbackDict[key] || key
    },
    [locale]
  )

  return { t, locale }
}
